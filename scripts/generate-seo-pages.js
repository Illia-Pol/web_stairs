function renderHead(page, extraSchemas = [], extraScripts = []) {
  const schemas = [localBusinessSchema(), ...extraSchemas]
    .map((schema) => `<script type="application/ld+json">${JSON.stringify(schema, null, 2)}</script>`)
    .join("\n  ");

  return `
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${page.title}</title>
  <meta name="description" content="${page.description}">
  <link rel="canonical" href="${SITE_URL}/${page.slug}/">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Oswald:wght@400;500;700&family=IBM+Plex+Sans:wght@300;400;500;600&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="/styles.css">
  <link rel="stylesheet" href="/assets/css/inner-pages.css">
  ${schemas}
  <script src="/assets/js/contacts.js" defer></script>
  ${extraScripts.join("\n  ")}
  <script src="/assets/js/inner-pages.js" defer></script>
</head>`;
}

function renderPage(page, options = {}) {
  const schemas = [faqSchema(page.faq)];
  if (page.service) schemas.push(serviceSchema(page, page.service));

  const scripts = [];
  if (options.includeProjectsScript) {
    scripts.push('<script src="/assets/data/projects.js" defer></script>');
  }

  return `<!doctype html>
<html lang="ru">
${renderHead(page, schemas, scripts)}
<body>
  ${renderHeader()}

  <main>
    <section class="section section-dark page-hero">
      <div class="container">
        ${renderBreadcrumbs(page.h1)}
        <p class="kicker">BETOSTEP</p>
        <h1>${page.h1}</h1>
        <p class="lead page-intro">${page.intro}</p>
      </div>
    </section>

    <section class="section">
      <div class="container page-content">
        ${renderCards(page.cards)}
      </div>
    </section>

    ${renderCta(page)}
    ${renderFaq(page.faq)}
  </main>

  ${renderFooter()}
</body>
</html>`;
}

function writePage(slug, html) {
  const dir = path.join(root, slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), html);
}

function createServiceAndStaticPages() {
  servicePages.forEach((page) => {
    writePage(page.slug, renderPage(page));
  });

  staticPages.forEach((page) => {
    writePage(page.slug, renderPage(page, { includeProjectsScript: page.needsProjectsScript }));
  });
}

